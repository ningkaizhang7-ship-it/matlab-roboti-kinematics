
x = [6 8 10 12 14 16 18]; 
y1 = [9.5 10.2 12.3 14.8 17.8 15.3 13.0]; 
y2 = [5.0 7.7 10.3 13.2 15.8 12.3 10.0];


xq = 6.5:2:17.5; 
yq1 = spline(x,y1,xq); 
yq2 = spline(x,y2,xq); 

% 使用plot函数绘制插值曲线和数据点
plot(x,y1,'o',xq,yq1,'-',x,y2,'o',xq,yq2,'-')
legend('室内数据点','室内插值曲线','室外数据点','室外插值曲线')
xlabel('时间')
ylabel('温度')
title('三次样条插值示例')
